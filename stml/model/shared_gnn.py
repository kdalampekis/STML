"""A relational graph encoder whose message passing can be shared across domains (structure vs content, TEM-style).

The original RelationalGNN has one weight matrix per edge type, so ARC (5 edge types) and logic (8) cannot share
anything but trivial layers. Here the relation enters as a learned *embedding*:

    message(u -> v, relation r) = MLP_l([h_u, e_r])           MLP_l is SHARED across domains
    h_v <- h_v + ReLU(LayerNorm(W_l h_v + sum_r mean_{u in N_r(v)} message(u -> v, r)))

  SharedCore      the shared part: message MLPs, self weights, norms, read-out (the "structure" machinery)
  DomainEncoder   per domain: input adapter (node features -> d) and a relation-embedding table (the "content" interface)

To transfer: train DomainEncoder(core, ...) on a source domain, then build a new DomainEncoder for the target with a copy of
the trained core and fresh adapter / relation table. `freeze_core` gives a linear-probe style test of the representation.
"""

from __future__ import annotations

import copy

import torch
import torch.nn as nn
import torch.nn.functional as F

from .network import GraphBatch


class SharedCore(nn.Module):
    def __init__(self, d: int = 64, layers: int = 4, d_rel: int = 32, mode: str = "concat", rank: int = 16):
        super().__init__()
        self.d, self.d_rel, self.layers, self.mode, self.rank = d, d_rel, layers, mode, rank
        # lowrank: message = W0 h + U((V h) * s_r) + b_r   (shared base, relation-specific low-rank part, s_r = Linear(e_r))
        # hyper:   message = W_r h + b_r with W_r = reshape(Linear(e_r))  (the original per-relation matrices, generated by a shared network)
        if mode == "lowrank":
            self.base = nn.ModuleList(nn.Linear(d, d) for _ in range(layers))
            self.V = nn.ModuleList(nn.Linear(d, rank, bias=False) for _ in range(layers))
            self.U = nn.ModuleList(nn.Linear(rank, d, bias=False) for _ in range(layers))
            self.S = nn.ModuleList(nn.Linear(d_rel, rank) for _ in range(layers))
            self.B = nn.ModuleList(nn.Linear(d_rel, d) for _ in range(layers))
        elif mode == "hyper":
            self.H = nn.ModuleList(nn.Linear(d_rel, d * d, bias=False) for _ in range(layers))
            self.B = nn.ModuleList(nn.Linear(d_rel, d) for _ in range(layers))
        # concat: MLP([h_u, e_r]); film: the relation multiplicatively gates (and shifts) the source state before a shared MLP;
        # both: concat plus the gate
        self.msg = nn.ModuleList(nn.Sequential(nn.Linear(d + (d_rel if mode != "film" else 0), d), nn.ReLU(), nn.Linear(d, d)) for _ in range(layers)) if mode in ("concat", "film", "both") else nn.ModuleList()
        if mode in ("film", "both"):
            self.gate = nn.ModuleList(nn.Linear(d_rel, d) for _ in range(layers))
            self.shift = nn.ModuleList(nn.Linear(d_rel, d) for _ in range(layers))
        self.self_w = nn.ModuleList(nn.Linear(d, d) for _ in range(layers))
        self.norm = nn.ModuleList(nn.LayerNorm(d) for _ in range(layers))
        self.out = nn.Linear(2 * d, d)


class DomainEncoder(nn.Module):
    """Drop-in replacement for RelationalGNN (same `nodes` and `forward` interface)."""

    def __init__(self, core: SharedCore, node_dim: int, n_types: int):
        super().__init__()
        self.core, self.n_types, self.d = core, n_types, core.d
        self.inp = nn.Linear(node_dim, core.d)
        self.rel = nn.Embedding(n_types, core.d_rel)

    def nodes(self, b: GraphBatch) -> torch.Tensor:
        c = self.core
        h = F.relu(self.inp(b.x))
        n = h.shape[0]
        for li, (ws, ln) in enumerate(zip(c.self_w, c.norm)):
            agg = torch.zeros(n, c.d, device=h.device)
            if b.src.numel():
                r = self.rel(b.etype)
                if c.mode == "lowrank":
                    m = c.base[li](h)[b.src] + c.U[li](c.V[li](h)[b.src] * c.S[li](r)) + c.B[li](r)
                elif c.mode == "hyper":
                    Wr = c.H[li](self.rel.weight).view(self.n_types, c.d, c.d)          # one matrix per relation, from its embedding
                    allrel = torch.einsum("nd,tkd->ntk", h, Wr)                            # every node under every relation
                    m = allrel[b.src, b.etype] + c.B[li](r)
                else:
                    hs = h[b.src]
                    if c.mode in ("film", "both"):
                        hs = hs * (1 + c.gate[li](r)) + c.shift[li](r)
                    m = c.msg[li](torch.cat([hs, r], 1) if c.mode != "film" else hs)    # [E, d]
                key = b.dst * self.n_types + b.etype
                cnt = torch.zeros(n * self.n_types, device=h.device).index_add_(0, key, torch.ones_like(key, dtype=torch.float32))
                summed = torch.zeros(n * self.n_types, c.d, device=h.device).index_add_(0, key, m)
                agg = (summed / cnt.clamp(min=1).unsqueeze(1)).view(n, self.n_types, c.d).sum(1)
            h = h + F.relu(ln(ws(h) + agg))
        return h

    def forward(self, b: GraphBatch) -> torch.Tensor:
        h = self.nodes(b)
        n = h.shape[0]
        counts = torch.zeros(b.n_graphs, device=h.device).index_add_(0, b.graph, torch.ones(n, device=h.device))
        mean = torch.zeros(b.n_graphs, self.d, device=h.device).index_add_(0, b.graph, h) / counts.clamp(min=1).unsqueeze(1)
        dense = torch.full((b.n_graphs, b.max_nodes, self.d), -1e4, device=h.device)
        dense[b.graph, b.pos] = h
        return self.core.out(torch.cat([mean, dense.max(1).values], 1))


def transfer_core(source: SharedCore | None, d: int = 64, layers: int = 4, d_rel: int = 32, freeze: bool = False, mode: str = "concat", rank: int = 16) -> SharedCore:
    """A core for a new domain: a copy of the source core (None = fresh random init)."""
    core = copy.deepcopy(source) if source is not None else SharedCore(d, layers, d_rel, mode, rank)
    core.requires_grad_(not freeze)
    return core
